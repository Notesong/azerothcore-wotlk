"""Assemble the client addon; no game files or running processes are changed."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / "addons" / "Mangosbot"
protocol = (ADDON / "MangosbotAcore.lua").read_text(encoding="utf-8-sig").rstrip()
ui = (ADDON / "MangosbotUI.lua").read_text(encoding="utf-8-sig").rstrip()
header = """-- Generated by scripts/Prepare-Mangosbot-Addon.py from the two source Lua files.
-- Standalone main also supports a running client's cached original TOC/XML load list.
if MangosbotFrame then return end
if not MangosbotAcore then
-- BEGIN EMBEDDED AZEROTHCORE PROTOCOL
"""
combined = header + protocol + "\n-- END EMBEDDED AZEROTHCORE PROTOCOL\nend\n" + ui + "\n"
(ADDON / "Mangosbot.lua").write_text(combined, encoding="utf-8", newline="\n")
print("Prepared addons/Mangosbot/Mangosbot.lua (standalone Lua 5.1 runtime).")
